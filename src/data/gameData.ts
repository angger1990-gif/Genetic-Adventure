export function getBossForLevel(levelId: number): BossInfo {
  const level = LEVELS.find((l) => l.id === levelId);
  const emojis: Record<number, string> = {
    1: '👺',
    2: '🌺',
    3: '🐇',
    4: '🔮',
    5: '🌽',
    6: '🧬',
  };
  return {
    id: `boss_${levelId}`,
    name: level?.bossName || 'Genetic Boss',
    hp: level?.bossHp || 600,
    maxHp: level?.bossHp || 600,
    avatarEmoji: emojis[levelId] || '👾',
    rewardXp: 500 + levelId * 150,
    rewardCoins: 50 + levelId * 25,
    crystalReward: level?.crystalId || levelId,
  };
}

